"""Build js/icons.js from the icon files in images/icons/.

Every icon is a normal SVG file (images/icons/flask.svg, images/icons/leaf.svg, ...).
The website shows an icon with <svg class="ic"><use href="#i-flask"/></svg>, which needs
the icons to be inside the page. Browsers refuse to load them from a separate file when
a page is opened straight from disk (file://), so this script copies them into a small
JavaScript file that puts them into each page.

Run it after you add or change an icon:

    python python/build_icons.py

favicon.svg is the browser-tab icon and is not included. Any <metadata> block inside an
icon file (added by some editors and apps) is left out, so the sprite stays small.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
ICON_DIR = ROOT / "images" / "icons"
OUT = ROOT / "js" / "icons.js"
SKIP = {"favicon"}

ROOT_TAG = re.compile(r"<svg\b([^>]*)>(.*)</svg>", re.S)
VIEWBOX = re.compile(r'viewBox="([^"]+)"')
METADATA = re.compile(r"<metadata\b.*?</metadata>", re.S)


def symbol(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    match = ROOT_TAG.search(text)
    if not match:
        raise ValueError(f"{path.name}: no <svg> element found")
    attrs, inner = match.groups()
    box = VIEWBOX.search(attrs)
    if not box:
        raise ValueError(f"{path.name}: the <svg> element needs a viewBox")
    inner = METADATA.sub("", inner)
    inner = " ".join(inner.split()).replace("'", "\\'")
    return f'<symbol id="i-{path.stem}" viewBox="{box.group(1)}">{inner}</symbol>'


def main() -> int:
    files = sorted(p for p in ICON_DIR.glob("*.svg") if p.stem not in SKIP)
    if not files:
        print(f"No icons found in {ICON_DIR}")
        return 1
    lines = [f"    '{symbol(p)}'" for p in files]
    js = (
        "/* ChemLab Explorer — icon sprite.\n"
        "   Generated by python/build_icons.py from the SVG files in images/icons/.\n"
        "   Do not edit this file by hand: change or add an icon in images/icons/, then run\n"
        "   python python/build_icons.py\n"
        "   (Pages opened straight from disk cannot load icons from a separate .svg file,\n"
        "   so they are placed into the page from here.) */\n"
        "(function () {\n"
        "  var symbols = [\n"
        + ",\n".join(lines)
        + "\n  ];\n"
        '  document.body.insertAdjacentHTML("afterbegin", \'<svg class="icon-sprite" xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false">\' + symbols.join("") + "</svg>");\n'
        "})();\n"
    )
    OUT.write_text(js, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} with {len(files)} icons.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
